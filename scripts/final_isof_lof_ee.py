    df = pd.read_csv(io.StringIO(text), delim_whitespace=True, header=0)

    # Mengubah tipe data kolom 'value' menjadi float
    df['value'] = df['value'].astype(float)

    # Menghitung nilai persentil 90%
    percentile_90 = df['value'].quantile(0.90)

    # Menyaring source_file yang nilainya di atas persentil 90%
    result = df[df['value'] > percentile_90]

    return result

