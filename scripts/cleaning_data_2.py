import pandas as pd
df=pd.read_csv('data_round.csv')

import seaborn as sns
import matplotlib.pyplot as plt
dfNum=['f1','f2','f3','f4','f5','f6','f7','f8','v1','v2','v3','v4','v5','v6','v7','v8']
# Pastikan hanya kolom numerik yang diproses
df_num = df[dfNum]

# Menghitung Q1 dan Q3 serta IQR
Q1 = df_num.quantile(0.25)
Q3 = df_num.quantile(0.75)
IQR = Q3 - Q1

# Menghitung batas outliers
maximum = Q3 + 1.5 * IQR
minimum = Q1 - 1.5 * IQR

# Handling outliers hanya pada kolom numerik
df_num = df_num.mask(df_num > maximum, maximum, axis=1)
df_num = df_num.mask(df_num < minimum, minimum, axis=1)

# Update kembali df dengan hasil baru
df[dfNum] = df_num

# Menampilkan deskripsi dari persebaran data yang sudah ditangani
print(df[dfNum].describe())

df.to_csv('data_round_clean.csv')
df.describe()
dfnew=df.drop(columns=['Unnamed: 0.1','source_file','max_v','max_f','t'])
display(dfnew)

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import GridSearchCV
from jcopml.tuning import grid_search_params as gsp

from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer

from jcopml.pipeline import num_pipe, cat_pipe
from jcopml.plot import plot_missing_value
from jcopml.feature_importance import mean_score_decrease

gsp.rf_params

X = dfnew[['f1','f2','f3','f4','f5','f6','f7','f8']]
y = dfnew[['v1','v2','v3','v4','v5','v6','v7','v8']]

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)
X_train.shape, X_test.shape, y_train.shape, y_test.shape

from sklearn.multioutput import MultiOutputRegressor
from sklearn.ensemble import RandomForestRegressor
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.model_selection import GridSearchCV

# Definisikan RandomForestRegressor dengan max_depth
rf = RandomForestRegressor(max_depth=5, n_jobs=-1, random_state=42)

# Gunakan RandomForestRegressor sebagai estimator untuk MultiOutputRegressor
multi_target_forest = MultiOutputRegressor(estimator=rf)

preprocessor = ColumnTransformer([
    ('numeric', num_pipe(), ['f1','f2','f3','f4','f5','f6','f7','f8']),
])

pipeline = Pipeline([
    ('prep', preprocessor),
    ('algo', multi_target_forest)  # Gunakan multi_target_forest yang telah didefinisikan
])

# Definisikan parameter grid untuk GridSearchCV
param_grid = {
    'algo__estimator__max_depth': [5, 10, 15],  # Gunakan notasi yang benar
    # Tambahkan parameter lain yang ingin Anda optimalkan
}

modelRF = GridSearchCV(pipeline, param_grid, cv=3, scoring='neg_mean_squared_error', n_jobs=-1, verbose=1)
modelRF.fit(X_train, y_train)

print(modelRF.best_params_)
from sklearn.metrics import r2_score

# Prediksi pada data uji
y_pred = modelRF.predict(X_test)

# Hitung R-squared
r2 = r2_score(y_test, y_pred)
print(f'R-squared: {r2}')
print(modelRF.score(X_train, y_train), modelRF.best_score_, modelRF.score(X_test, y_test))

# Predict on test data
y_pred = modelRF.predict(X_test)

# Convert X_test to a DataFrame for easier manipulation
X_test_df = pd.DataFrame(X_test, columns=['f1', 'f2', 'f3', 'f4', 'f5', 'f6', 'f7', 'f8'])

# Convert y_pred to a DataFrame for easier manipulation
y_pred_df = pd.DataFrame(y_pred, columns=['v1', 'v2', 'v3', 'v4', 'v5', 'v6', 'v7', 'v8'])

# Create a combined plot
plt.figure(figsize=(10, 6))

colors = sns.color_palette("hsv", len(X_test_df.columns))

for i, (feature, target) in enumerate(zip(X_test_df.columns, y_pred_df.columns)):
    sns.scatterplot(x=X_test_df[feature], y=y_pred_df[target], label=f'{feature} vs {target}', color=colors[i])

plt.xlabel('Features')
plt.ylabel('Predicted Targets')
plt.title('Features vs Predicted Targets')
plt.grid(True)
plt.legend()
plt.show()
