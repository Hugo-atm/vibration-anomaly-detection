# Membangun Autoencoder
encoding_dim = 2  # Ukuran latent space
input_dim = 1  # Karena hanya ada satu fitur 'v'

seed = 42
np.random.seed(seed)
tf.random.set_seed(seed)
random.seed(seed)


autoencoder = Sequential([
    Input(shape=(input_dim,)),
    Dense(16, activation='relu'),
    Dense(8, activation='relu'),
    Dense(encoding_dim, activation='relu', name='latent_space'),
    Dense(8, activation='relu'),
    Dense(16, activation='relu'),
    Dense(input_dim)
])

autoencoder.compile(optimizer='adam', loss='mse')

fig, axes = plt.subplots(4, 5, figsize=(20, 20))  # 4 baris, 5 kolom
axes = axes.flatten()

# Loop untuk setiap nilai f yang unik dalam rentang 1 hingga 10
for idx, f_value in enumerate(unique_f_values):
    # Filter data untuk f tertentu
    subset_data = filtered_data[filtered_data['f'] == f_value]

    if len(subset_data) > 1:  # Pastikan ada lebih dari satu sampel
        # Latih model Autoencoder
        autoencoder.fit(subset_data[['v']], subset_data[['v']], epochs=50, batch_size=16, shuffle=True, verbose=0)

        # Rekonstruksi data
        reconstructed_data = autoencoder.predict(subset_data[['v']])

        # Hitung reconstruction error
        reconstruction_error = np.mean(np.abs(subset_data[['v']] - reconstructed_data), axis=1)

        # Menentukan threshold untuk anomali
        threshold = np.percentile(reconstruction_error, 90)  # Contoh threshold

        # Menentukan label berdasarkan threshold
        labels = (reconstruction_error > threshold).astype(int)

        # Plotting
        ax = axes[idx]
        scatter = ax.scatter(subset_data['f'], subset_data['v'], c=labels, cmap='viridis', label=None)

        # Tambahkan nama file ke legenda jika warnanya ungu
        colors = scatter.to_rgba(labels)
        for i, color in enumerate(colors):
            if tuple(color)[:3] == tuple(yellow_color[:3]):
                ax.scatter(subset_data['f'].iloc[i], subset_data['v'].iloc[i], c=[color], label=subset_data['source_file'].iloc[i])

        ax.set_xlabel('v')
        ax.set_ylabel('f')
        ax.set_xticks([f_value])
        ax.set_title(f'Autoencoder f={f_value}')
        ax.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
        ax.grid(True)

